export async function GET() {
  const items = articles.map((a) => `
    <item turbo="true">
      <title>${a.title}</title>
      <link>${a.url}</link>
      <description>${a.description}</description>
      <pubDate>${new Date(a.date).toUTCString()}</pubDate>
      <turbo:content>
        <![CDATA[
          ${a.content}
          <p><a href="${a.url}">Читать полностью на сайте клуба «Медведь»</a></p>
        ]]>
      </turbo:content>
    </item>`).join("\n")

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:turbo="http://turbo.yandex.ru">
  <channel>
    <title>Клуб тайского бокса «Медведь» — Блог</title>
    <link>${BASE}/blog</link>
    <description>Статьи о тайском боксе: для новичков, детей, взрослых и родителей</description>
    <language>ru</language>
    ${items}
  </channel>
</rss>`

  return new NextResponse(xml, {
    headers: { "Content-Type": "application/rss+xml; charset=utf-8" },
  })
}
